/**
 * Shared body builder for every generated mode artefact.
 *
 * All three agents receive the same semantic content (role, when to use,
 * workflow) - only the wrapper (frontmatter / title) differs per product, which
 * keeps the per-agent renderers tiny and the behaviour easy to compare.
 */

/**
 * @param {string} slug
 * @returns {string} HTML comment marking the file as generated
 */
export function autogeneratedNotice(slug) {
  return [
    `<!-- AUTOGENERATED from .roomodes mode "${slug}" - do not edit by hand. -->`,
    '<!-- Regenerate by running: scripts/init.ps1 or scripts/init.sh -->',
  ].join('\n');
}

/**
 * Render the shared markdown body of a mode.
 *
 * @param {import('./roomodes.mjs').Roomode} mode
 * @returns {string} markdown body, one trailing newline
 */
export function renderModeBody(mode) {
  const sections = [
    `## Role\n\n${trimBlock(mode.roleDefinition)}`,
    `## When to use\n\n${trimBlock(mode.whenToUse)}`,
  ];

  const instructions = trimBlock(mode.customInstructions ?? '');
  if (instructions !== '') {
    sections.push(`## Workflow\n\n${instructions}`);
  }

  return `${sections.join('\n\n')}\n`;
}

/**
 * Trim trailing whitespace and normalise line endings of a YAML block scalar.
 *
 * @param {string} value
 * @returns {string}
 */
export function trimBlock(value) {
  return String(value).replace(/\r\n/g, '\n').replace(/\s+$/u, '');
}

/**
 * Render a YAML flow sequence (`['a', 'b']`) with single quotes.
 *
 * @param {string[]} values
 * @returns {string}
 */
export function toFlowSequence(values) {
  return `[${values.map((value) => `'${value.replace(/'/g, "''")}'`).join(', ')}]`;
}

/**
 * Ensure a string ends with exactly one newline.
 *
 * @param {string} content
 * @returns {string}
 */
export function withSingleTrailingNewline(content) {
  return `${content.replace(/\s+$/u, '')}\n`;
}
