/**
 * Claude Code subagent renderer.
 *
 * Output: `.claude/agents/<slug>.md` - a project-level subagent with its own
 * system prompt and tool allowlist, which is Claude Code's closest native
 * equivalent of a Zoo Code custom mode.
 */

import { autogeneratedNotice, renderModeBody, withSingleTrailingNewline } from './render-body.mjs';
import { toClaudeTools } from './tools.mjs';

/**
 * @param {import('./roomodes.mjs').Roomode} mode
 * @param {{ claudeTools?: string[] }} [overrides] per-mode overrides
 * @returns {{ relativePath: string, content: string }}
 */
export function renderClaudeSubagent(mode, overrides = {}) {
  const tools = toClaudeTools(mode.groups, overrides.claudeTools);
  const frontmatter = [
    '---',
    `name: ${mode.slug}`,
    `description: ${toSingleLine(buildDescription(mode))}`,
    `tools: ${tools.join(', ')}`,
    '---',
  ].join('\n');

  const content = [
    frontmatter,
    '',
    autogeneratedNotice(mode.slug),
    '',
    `# ${mode.name}`,
    '',
    renderModeBody(mode),
  ].join('\n');

  return {
    relativePath: `.claude/agents/${mode.slug}.md`,
    content: withSingleTrailingNewline(content),
  };
}

/**
 * Claude routes work by the `description`, so the "when to use" hint must be
 * part of it.
 *
 * @param {import('./roomodes.mjs').Roomode} mode
 * @returns {string}
 */
function buildDescription(mode) {
  const base = String(mode.description).trim().replace(/[.\s]+$/u, '');
  const hint = String(mode.whenToUse)
    .trim()
    .replace(/^Use (it|this mode) when /iu, '');
  return `${base}. Use when ${ensureSentenceEnd(lowerFirst(hint))}`;
}

/**
 * @param {string} value
 * @returns {string}
 */
function lowerFirst(value) {
  const text = String(value).trim();
  return text.charAt(0).toLowerCase() + text.slice(1);
}

/**
 * @param {string} value
 * @returns {string}
 */
function ensureSentenceEnd(value) {
  return /[.!?]$/u.test(value) ? value : `${value}.`;
}

/**
 * @param {string} value
 * @returns {string}
 */
function toSingleLine(value) {
  return String(value).replace(/\s+/gu, ' ').trim();
}
