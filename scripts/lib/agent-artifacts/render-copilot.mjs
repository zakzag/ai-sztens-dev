/**
 * GitHub Copilot chat mode renderer.
 *
 * Output: `.github/chatmodes/<slug>.chatmode.md` - VS Code picks these up as
 * selectable chat modes, which is the closest native equivalent of a Zoo Code
 * custom mode.
 */

import {
  autogeneratedNotice,
  renderModeBody,
  toFlowSequence,
  withSingleTrailingNewline,
} from './render-body.mjs';
import { toCopilotTools } from './tools.mjs';

/**
 * @param {import('./roomodes.mjs').Roomode} mode
 * @param {{ copilotTools?: string[] }} [overrides] per-mode overrides
 * @returns {{ relativePath: string, content: string }}
 */
export function renderCopilotChatMode(mode, overrides = {}) {
  const tools = toCopilotTools(mode.groups, overrides.copilotTools);
  const frontmatter = [
    '---',
    `description: ${toSingleLine(mode.description)}`,
    `tools: ${toFlowSequence(tools)}`,
    '---',
  ].join('\n');

  const content = [
    frontmatter,
    '',
    autogeneratedNotice(mode.slug),
    '',
    `# ${mode.name}`,
    '',
    renderModeBody(mode),
  ].join('\n');

  return {
    relativePath: `.github/chatmodes/${mode.slug}.chatmode.md`,
    content: withSingleTrailingNewline(content),
  };
}

/**
 * Frontmatter values must stay on one line.
 *
 * @param {string} value
 * @returns {string}
 */
function toSingleLine(value) {
  return String(value).replace(/\s+/gu, ' ').trim();
}
