/**
 * Cursor renderers.
 *
 * Cursor has no file-based custom chat mode, so a Zoo Code mode is expressed as
 * two artefacts:
 *   1. `.cursor/commands/<slug>.md` - an invocable "/<slug>" command (the closest
 *      thing to "switch into this mode"),
 *   2. `.cursor/rules/<slug>.mdc`   - an on-demand rule (`alwaysApply: false`)
 *      the user can reference with @, so the workflow is also available in the
 *      normal chat/agent flow.
 */

import { autogeneratedNotice, renderModeBody, withSingleTrailingNewline } from './render-body.mjs';

/**
 * @param {import('./roomodes.mjs').Roomode} mode
 * @returns {{ relativePath: string, content: string }}
 */
export function renderCursorCommand(mode) {
  const content = [
    autogeneratedNotice(mode.slug),
    '',
    `# ${mode.name}`,
    '',
    `Act as the "${mode.name}" mode described below for the rest of this task.`,
    '',
    renderModeBody(mode),
  ].join('\n');

  return {
    relativePath: `.cursor/commands/${mode.slug}.md`,
    content: withSingleTrailingNewline(content),
  };
}

/**
 * @param {import('./roomodes.mjs').Roomode} mode
 * @returns {{ relativePath: string, content: string }}
 */
export function renderCursorRule(mode) {
  const frontmatter = [
    '---',
    `description: ${toSingleLine(mode.description)}`,
    'globs:',
    'alwaysApply: false',
    '---',
  ].join('\n');

  const content = [
    frontmatter,
    '',
    autogeneratedNotice(mode.slug),
    '',
    `# ${mode.name}`,
    '',
    renderModeBody(mode),
  ].join('\n');

  return {
    relativePath: `.cursor/rules/${mode.slug}.mdc`,
    content: withSingleTrailingNewline(content),
  };
}

/**
 * @param {string} value
 * @returns {string}
 */
function toSingleLine(value) {
  return String(value).replace(/\s+/gu, ' ').trim();
}
