/**
 * `.roo/rules/*.md` discovery and instruction-file rendering.
 *
 * Contract (unchanged from the original shell implementation):
 *   - every `*.md` directly under `.roo/rules/` is a source (non-recursive),
 *   - zero-byte files and `~$*` temp files are skipped,
 *   - `instructions.md` is emitted first, everything else in byte order,
 *   - the rendered file gets one header, one `## Source:` block per file and
 *     exactly one trailing newline.
 */

import { readdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';

export const RULES_DIR = '.roo/rules';
export const PRIMARY_RULE_FILE = 'instructions.md';
const EM_DASH = '\u2014';

/**
 * @typedef {{ relativePath: string, content: string }} Artifact
 */

/**
 * @typedef {object} AgentSpec
 * @property {string} target path of the generated instruction file
 * @property {'md' | 'mdc'} format `mdc` prepends the Cursor frontmatter
 */

/** @type {Record<'copilot' | 'cursor' | 'claude', AgentSpec>} */
export const AGENT_SPECS = Object.freeze({
  copilot: { target: '.github/copilot-instructions.md', format: 'md' },
  cursor: { target: '.cursor/rules/project.mdc', format: 'mdc' },
  claude: { target: 'CLAUDE.md', format: 'md' },
});

/**
 * @param {string} name
 * @returns {boolean}
 */
export function isRuleSourceName(name) {
  return name.endsWith('.md') && !name.startsWith('~$');
}

/**
 * Order rule file names: primary first, then byte order.
 *
 * @param {string[]} names
 * @returns {string[]}
 */
export function orderRuleNames(names) {
  const sorted = [...names].sort((left, right) => (left < right ? -1 : left > right ? 1 : 0));
  return [
    ...sorted.filter((name) => name === PRIMARY_RULE_FILE),
    ...sorted.filter((name) => name !== PRIMARY_RULE_FILE),
  ];
}

/**
 * Discover the rule sources under `<repoRoot>/.roo/rules`.
 *
 * @param {string} repoRoot absolute repository root
 * @returns {Promise<{ sources: string[], missingPrimary: boolean }>}
 * @throws {Error} when the rules directory is missing
 */
export async function discoverRuleSources(repoRoot) {
  const directory = join(repoRoot, RULES_DIR);
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    throw new Error(`Cannot read ${RULES_DIR}/: ${error.message}`);
  }

  /** @type {string[]} */
  const names = [];
  for (const entry of entries) {
    if (!entry.isFile() || !isRuleSourceName(entry.name)) {
      continue;
    }
    const content = await readFile(join(directory, entry.name), 'utf8');
    if (content.length === 0) {
      continue;
    }
    names.push(entry.name);
  }

  const ordered = orderRuleNames(names);
  return {
    sources: ordered.map((name) => `${RULES_DIR}/${name}`),
    missingPrimary: !ordered.includes(PRIMARY_RULE_FILE),
  };
}

/**
 * Render the concatenated instruction content for an agent.
 *
 * @param {'copilot' | 'cursor' | 'claude'} agent
 * @param {string} repoRoot absolute repository root
 * @param {string[]} sources relative rule source paths (already ordered)
 * @returns {Promise<Artifact>}
 */
export async function renderInstructionFile(agent, repoRoot, sources) {
  const spec = AGENT_SPECS[agent];
  if (spec === undefined) {
    throw new Error(`Unknown agent "${agent}" (known: ${Object.keys(AGENT_SPECS).join(', ')})`);
  }

  /** @type {string[]} */
  const bodyParts = [];
  for (const source of sources) {
    const content = await readFile(join(repoRoot, source), 'utf8');
    const normalised = content.replace(/\r\n/g, '\n');
    bodyParts.push(`---\n\n## Source: ${source}\n\n${normalised.endsWith('\n') ? normalised : `${normalised}\n`}`);
  }

  const header = [
    `# AI Agent Instructions ${EM_DASH} autogenerated from .roo/rules/`,
    '',
    '<!-- DO NOT EDIT THIS FILE MANUALLY. -->',
    `<!-- Source of truth: .roo/rules/ ${EM_DASH} edit those files instead. -->`,
    '<!-- Regenerate by running: scripts/init.ps1 or scripts/init.sh -->',
    '',
  ].join('\n');

  const frontmatter =
    spec.format === 'mdc'
      ? [
          '---',
          `description: AIsztens ${EM_DASH} project + coding rules (autogenerated from .roo/rules/)`,
          'globs:',
          'alwaysApply: true',
          '---',
          '',
          '',
        ].join('\n')
      : '';

  const content = `${frontmatter}${header}${bodyParts.join('\n')}`.replace(/\s+$/u, '');
  return { relativePath: spec.target, content: `${content}\n` };
}
