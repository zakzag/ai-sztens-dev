/**
 * Idempotent file writer and `.gitignore` synchroniser.
 *
 * Contract (shared by every generated artefact):
 *   - UTF-8 without BOM, LF line endings, exactly one trailing newline,
 *   - unchanged content => nothing is written,
 *   - changed content => the previous file is kept next to it as `<path>.bak`,
 *   - every generated path AND its `.bak` counterpart is registered in the
 *     `.gitignore` "AI agent instruction files" section, idempotently and
 *     CRLF-tolerantly (so a file written by an older Windows run still matches).
 */

import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';

export const GITIGNORE_FILE = '.gitignore';
export const GITIGNORE_MARKER = '# --- AI agent instruction files (autogenerated by scripts/init.*) ---';
export const GITIGNORE_SOURCE_LINE = '# Source of truth: .roo/rules/ and .roomodes';

/**
 * @typedef {'written' | 'unchanged' | 'planned'} WriteResult
 */

/**
 * Write a generated artefact.
 *
 * @param {object} options
 * @param {string} options.repoRoot absolute repository root
 * @param {string} options.relativePath target path relative to the root
 * @param {string} options.content full file content
 * @param {boolean} [options.dryRun] compute the result without touching the disk
 * @returns {Promise<WriteResult>}
 */
export async function writeArtifact({ repoRoot, relativePath, content, dryRun = false }) {
  const target = join(repoRoot, relativePath);
  const existing = await readTextIfExists(target);

  // Byte-exact comparison on purpose: a stale BOM or CRLF written by an earlier
  // generator counts as a change, so the file gets rewritten without a BOM and
  // with LF endings (a BOM would break the Cursor `.mdc` frontmatter).
  if (existing === content) {
    return 'unchanged';
  }
  if (dryRun) {
    return 'planned';
  }

  await mkdir(dirname(target), { recursive: true });
  if (existing !== null) {
    await copyFile(target, `${target}.bak`);
  }
  await writeFile(target, content, { encoding: 'utf8' });
  return 'written';
}

/**
 * Register generated paths (and their `.bak` pairs) in `.gitignore`.
 *
 * `.roomodes` must never be passed in: it is the authored source and stays
 * tracked.
 *
 * @param {object} options
 * @param {string} options.repoRoot absolute repository root
 * @param {string[]} options.relativePaths generated artefacts that must be ignored
 * @param {boolean} [options.dryRun]
 * @returns {Promise<{ added: string[], skipped: string[], warning: string | null }>}
 */
export async function syncGitignore({ repoRoot, relativePaths, dryRun = false }) {
  const target = join(repoRoot, GITIGNORE_FILE);
  const existing = await readTextIfExists(target);
  if (existing === null) {
    return {
      added: [],
      skipped: relativePaths,
      warning: `${GITIGNORE_FILE} does not exist - add the generated paths manually`,
    };
  }

  const entries = relativePaths.flatMap((path) => (path === '.roomodes' ? [] : [path, `${path}.bak`]));
  const lines = existing.split('\n').map((line) => line.replace(/\r$/, ''));
  const added = [];
  for (const entry of entries) {
    if (!lines.includes(entry)) {
      added.push(entry);
    }
  }

  if (added.length === 0 || dryRun) {
    return { added, skipped: entries.filter((entry) => !added.includes(entry)), warning: null };
  }

  const hasMarker = lines.includes(GITIGNORE_MARKER);
  const body = trimTrailingBlankLines(lines);
  if (!hasMarker) {
    body.push('', GITIGNORE_MARKER, GITIGNORE_SOURCE_LINE);
  }
  body.push(...added);

  await writeFile(target, `${body.join('\n')}\n`, { encoding: 'utf8' });
  return { added, skipped: entries.filter((entry) => !added.includes(entry)), warning: null };
}

/**
 * @param {string} filePath
 * @returns {Promise<string | null>}
 */
async function readTextIfExists(filePath) {
  try {
    return await readFile(filePath, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') {
      return null;
    }
    throw error;
  }
}

/**
 * @param {string[]} lines
 * @returns {string[]}
 */
function trimTrailingBlankLines(lines) {
  const result = [...lines];
  while (result.length > 0 && result[result.length - 1].trim() === '') {
    result.pop();
  }
  return result;
}
