/**
 * Tests for the idempotent writer, the `.gitignore` synchroniser and the CLI
 * end-to-end behaviour (exit codes, `.bak`, staleness detection).
 */

import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { after, before, beforeEach, describe, it } from 'node:test';

import { syncGitignore, writeArtifact } from './writer.mjs';

const execFileAsync = promisify(execFile);
const CLI = join(dirname(fileURLToPath(import.meta.url)), 'generate.mjs');

const RULE_FILE = '# Instructions\n\nFirst rule.\n';
const ROOMODES = `customModes:
  - slug: jira-ticket-writer
    name: Jira Ticket Writer
    description: Writes Jira tickets
    roleDefinition: You are an expert task writer.
    whenToUse: Use it when the user asks for a JIRA issue.
    customInstructions: Read the docs first.
    groups:
      - read
      - command
`;

describe('writeArtifact', () => {
  /** @type {string} */
  let root;

  beforeEach(async () => {
    root = await mkdtemp(join(tmpdir(), 'writer-'));
  });

  after(async () => {
    await rm(root, { recursive: true, force: true });
  });

  it('writes a new file as UTF-8 without BOM and with LF endings', async () => {
    const status = await writeArtifact({
      repoRoot: root,
      relativePath: 'a/b.md',
      content: 'x\ny\n',
    });
    assert.equal(status, 'written');
    const raw = await readFile(join(root, 'a/b.md'));
    assert.deepEqual([...raw], [0x78, 0x0a, 0x79, 0x0a]);
  });

  it('is idempotent', async () => {
    await writeArtifact({
      repoRoot: root,
      relativePath: 'file.md',
      content: 'x\n',
    });
    const status = await writeArtifact({
      repoRoot: root,
      relativePath: 'file.md',
      content: 'x\n',
    });
    assert.equal(status, 'unchanged');
  });

  it('keeps the previous content as .bak when the content changes', async () => {
    await writeArtifact({
      repoRoot: root,
      relativePath: 'file.md',
      content: 'old\n',
    });
    const status = await writeArtifact({
      repoRoot: root,
      relativePath: 'file.md',
      content: 'new\n',
    });
    assert.equal(status, 'written');
    assert.equal(await readFile(join(root, 'file.md.bak'), 'utf8'), 'old\n');
    assert.equal(await readFile(join(root, 'file.md'), 'utf8'), 'new\n');
  });

  it('ignores a BOM written by an earlier run', async () => {
    await mkdir(root, { recursive: true });
    await writeFile(join(root, 'file.md'), '\uFEFFx\n', 'utf8');
    const status = await writeArtifact({
      repoRoot: root,
      relativePath: 'file.md',
      content: 'x\n',
    });
    assert.equal(
      status,
      'written',
      'BOM-only difference is treated as a change',
    );
    assert.equal(await readFile(join(root, 'file.md'), 'utf8'), 'x\n');
  });

  it('reports planned writes in dry-run mode', async () => {
    const status = await writeArtifact({
      repoRoot: root,
      relativePath: 'file.md',
      content: 'x\n',
      dryRun: true,
    });
    assert.equal(status, 'planned');
  });
});

describe('syncGitignore', () => {
  /** @type {string} */
  let root;

  beforeEach(async () => {
    root = await mkdtemp(join(tmpdir(), 'gitignore-'));
  });

  after(async () => {
    await rm(root, { recursive: true, force: true });
  });

  it('creates the marker section and adds the file plus its .bak', async () => {
    await writeFile(join(root, '.gitignore'), 'node_modules/\n', 'utf8');
    const result = await syncGitignore({
      repoRoot: root,
      relativePaths: ['.cursor/commands/x.md'],
    });

    assert.deepEqual(result.added, [
      '.cursor/commands/x.md',
      '.cursor/commands/x.md.bak',
    ]);
    const content = await readFile(join(root, '.gitignore'), 'utf8');
    assert.match(
      content,
      /# --- AI agent instruction files \(autogenerated by scripts\/init\.\*\) ---/u,
    );
    assert.match(
      content,
      /\.cursor\/commands\/x\.md\n\.cursor\/commands\/x\.md\.bak\n$/u,
    );
  });

  it('is idempotent and tolerates CRLF entries written earlier', async () => {
    await writeFile(
      join(root, '.gitignore'),
      'node_modules/\r\n.cursor/commands/x.md\r\n',
      'utf8',
    );
    const result = await syncGitignore({
      repoRoot: root,
      relativePaths: ['.cursor/commands/x.md'],
    });

    assert.deepEqual(result.added, ['.cursor/commands/x.md.bak']);
    const content = await readFile(join(root, '.gitignore'), 'utf8');
    assert.equal(
      content.split('\n').filter((line) => line === '.cursor/commands/x.md')
        .length,
      1,
    );
  });

  it('never adds .roomodes', async () => {
    await writeFile(join(root, '.gitignore'), '', 'utf8');
    const result = await syncGitignore({
      repoRoot: root,
      relativePaths: ['.roomodes'],
    });
    assert.deepEqual(result.added, []);
  });

  it('warns when .gitignore is missing', async () => {
    const result = await syncGitignore({
      repoRoot: root,
      relativePaths: ['x.md'],
    });
    assert.match(String(result.warning), /does not exist/u);
  });
});

describe('generate.mjs CLI', () => {
  /** @type {string} */
  let root;

  before(async () => {
    root = await mkdtemp(join(tmpdir(), 'cli-'));
    await mkdir(join(root, '.roo/rules'), { recursive: true });
    await writeFile(
      join(root, '.roo/rules/instructions.md'),
      RULE_FILE,
      'utf8',
    );
    await writeFile(join(root, '.roomodes'), ROOMODES, 'utf8');
    await writeFile(join(root, '.gitignore'), 'node_modules/\n', 'utf8');
  });

  after(async () => {
    await rm(root, { recursive: true, force: true });
  });

  it('exits 2 on --check when nothing was generated yet', async () => {
    await assert.rejects(
      () =>
        execFileAsync(process.execPath, [
          CLI,
          '--agent',
          'cursor',
          '--root',
          root,
          '--check',
        ]),
      (error) => error.code === 2,
    );
  });

  it('generates the artefacts and registers them in .gitignore', async () => {
    await execFileAsync(process.execPath, [
      CLI,
      '--agent',
      'cursor',
      '--root',
      root,
    ]);

    assert.match(
      await readFile(
        join(root, '.cursor/commands/jira-ticket-writer.md'),
        'utf8',
      ),
      /## Role/u,
    );
    assert.match(
      await readFile(
        join(root, '.cursor/rules/jira-ticket-writer.mdc'),
        'utf8',
      ),
      /alwaysApply: false/u,
    );
    assert.match(
      await readFile(join(root, '.cursor/rules/project.mdc'), 'utf8'),
      /## Source: .roo\/rules\/instructions\.md/u,
    );

    const gitignore = await readFile(join(root, '.gitignore'), 'utf8');
    assert.match(gitignore, /\.cursor\/commands\/jira-ticket-writer\.md\.bak/u);
    assert.match(gitignore, /\.cursor\/rules\/project\.mdc\.bak/u);
    assert.doesNotMatch(gitignore, /^\.roomodes$/mu);
  });

  it('exits 0 on --check after a successful generation and reports no staleness', async () => {
    const { stdout } = await execFileAsync(process.execPath, [
      CLI,
      '--agent',
      'cursor',
      '--root',
      root,
      '--check',
    ]);
    assert.doesNotMatch(stdout, /Elavult/u);
  });

  it('rejects an unknown agent', async () => {
    await assert.rejects(
      () =>
        execFileAsync(process.execPath, [
          CLI,
          '--agent',
          'nope',
          '--root',
          root,
        ]),
      (error) =>
        error.code === 1 && /--agent is required/u.test(String(error.stderr)),
    );
  });

  it('rejects unknown arguments', async () => {
    await assert.rejects(
      () =>
        execFileAsync(process.execPath, [
          CLI,
          '--agent',
          'cursor',
          '--root',
          root,
          '--wat',
        ]),
      (error) =>
        error.code === 1 && /Unknown argument/u.test(String(error.stderr)),
    );
  });
});
